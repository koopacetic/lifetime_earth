#!/usr/bin/env python3
"""Draw a line-art map of present-day land from Natural Earth GeoJSON (public domain).

    tools/basemap.py LAND.geojson OUT.svg --bbox W S E N [--width 500] \
        [--mark "lon,lat,label"]... [--label "lon,lat,text"]...

Land outlines are drawn as uniform black strokes (no fill), matching art/line/. Projection is
equirectangular scaled by cos(mid-latitude), fine for regional maps. Download the GeoJSON
(e.g. ne_50m_land.geojson from github.com/nvkelso/natural-earth-vector) into a scratch folder;
it is not kept in the repo. Add an art/credits.json record with "credits": ["claude-drawings", "naturalearth"]; cite marked facts in art.sources.
"""
import argparse
import json
import math


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("land")
    ap.add_argument("out")
    ap.add_argument("--bbox", nargs=4, type=float, required=True, metavar=("W", "S", "E", "N"))
    ap.add_argument("--width", type=float, default=500)
    ap.add_argument("--stroke", type=float, default=1.1)
    ap.add_argument("--mark", action="append", default=[], help="lon,lat,label: filled dot + label")
    ap.add_argument("--label", action="append", default=[], help="lon,lat,text: italic text only")
    ap.add_argument("--font", type=float, default=15)
    a = ap.parse_args()
    W, S, E, N = a.bbox
    k = math.cos(math.radians((S + N) / 2))
    sx = a.width / ((E - W) * k)
    height = (N - S) * sx

    def xy(lon, lat):
        return (lon - W) * k * sx, (N - lat) * sx

    rings = []
    for f in json.load(open(a.land, encoding="utf-8"))["features"]:
        g = f["geometry"]
        polys = g["coordinates"] if g["type"] == "MultiPolygon" else [g["coordinates"]]
        for poly in polys:
            for ring in poly:
                lons = [p[0] for p in ring]
                lats = [p[1] for p in ring]
                if max(lons) < W or min(lons) > E or max(lats) < S or min(lats) > N:
                    continue
                rings.append(" ".join(f"{x:.1f},{y:.1f}" for x, y in (xy(lo, la) for lo, la in ring)))
    o = [f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {a.width:.0f} {height:.0f}" '
         f'width="{a.width:.0f}" height="{height:.0f}" font-family="serif" font-size="{a.font}">',
         "  <!-- Land outlines: Natural Earth (public domain). Generated by tools/basemap.py. -->",
         f'  <svg x="0" y="0" width="{a.width:.0f}" height="{height:.0f}" viewBox="0 0 {a.width:.0f} {height:.0f}" overflow="hidden">',
         f'  <g fill="none" stroke="black" stroke-width="{a.stroke}" stroke-linejoin="round">']
    o += [f'    <polygon points="{r}"/>' for r in rings]
    o += ["  </g>", "  </svg>",
          f'  <rect x="0.5" y="0.5" width="{a.width - 1:.0f}" height="{height - 1:.0f}" fill="none" stroke="black" stroke-width="0.8"/>']
    for m in a.mark:
        lon, lat, lab = m.split(",", 2)
        x, y = xy(float(lon), float(lat))
        o.append(f'  <circle cx="{x:.1f}" cy="{y:.1f}" r="4.5" fill="black"/>')
        if lab:
            o.append(f'  <text x="{x + 8:.1f}" y="{y + 5:.1f}">{lab}</text>')
    for m in a.label:
        lon, lat, txt = m.split(",", 2)
        x, y = xy(float(lon), float(lat))
        o.append(f'  <text x="{x:.1f}" y="{y:.1f}" font-style="italic" text-anchor="middle">{txt}</text>')
    o.append("</svg>")
    open(a.out, "w", encoding="utf-8").write("\n".join(o) + "\n")
    print(f"-> {a.out} ({len(rings)} rings, {a.width:.0f}x{height:.0f})")


if __name__ == "__main__":
    main()
